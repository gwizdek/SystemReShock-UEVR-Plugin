<#
.SYNOPSIS
    Raises the plugin build index by one and writes the generated version header.

.DESCRIPTION
    Runs before every plugin build from a target in SystemShockVR\SystemShockVR.vcxproj.
    Reads SystemShockVR\build_index.txt, adds one, writes it back, and writes
    SystemShockVR\build_version_generated.hpp with the plugin version and the new index.
    The plugin version is InformationalVersion from the installer project file, so the
    plugin and the installer always show the same version.

.PARAMETER ProjectDir
    The SystemShockVR folder.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$ProjectDir
)

$ErrorActionPreference = 'Stop'

$indexFile = Join-Path $ProjectDir 'build_index.txt'
$headerFile = Join-Path $ProjectDir 'build_version_generated.hpp'
$installerProject = Join-Path $ProjectDir '..\SystemShockInstaller\src\SystemReShockInstaller\SystemReShockInstaller.csproj'

function Read-InformationalVersion([string]$Path) {
    [xml]$xml = Get-Content $Path
    foreach ($group in $xml.Project.PropertyGroup) {
        if ($group.InformationalVersion) { return [string]$group.InformationalVersion }
    }
    throw "InformationalVersion not found in $Path"
}

$index = 0
if (Test-Path $indexFile) {
    $index = [int](Get-Content $indexFile -Raw).Trim()
}
$index++
Set-Content -Path $indexFile -Value "$index" -NoNewline -Encoding ascii

$version = Read-InformationalVersion $installerProject
$header = @"
// Generated by scripts\bump-build-index.ps1 before every plugin build. Not tracked by git.
#pragma once
#define PLUGIN_VERSION "$version"
#define PLUGIN_BUILD_INDEX $index
"@
Set-Content -Path $headerFile -Value $header -Encoding ascii
Write-Host "Plugin version $version build $index"
