#include "BridgeHeaderBuilder.h"

#include "BridgeContext.h"
#include "BridgeNaming.h"
#include "UObject/Class.h"

FBridgeHeaderBuilder::FBridgeHeaderBuilder(const FBridgeContext& InContext, const UField* InSelf)
    : Context(InContext)
    , Self(InSelf)
{
}

void FBridgeHeaderBuilder::AddDeps(const TArray<FBridgeDep>& Deps)
{
    for (const FBridgeDep& Dep : Deps)
    {
        AddDep(Dep);
    }
}

void FBridgeHeaderBuilder::AddDep(const FBridgeDep& Dep)
{
    if (Dep.Field == nullptr || Dep.Field == Self)
    {
        return;
    }
    const UClass* Class = Cast<UClass>(Dep.Field);
    if (Dep.bComplete || Class == nullptr)
    {
        Includes.Add(IncludeFor(Dep.Field));
        return;
    }
    ForwardDecls.Add(TEXT("class ") + BridgeNaming::ClassCppName(Class) + TEXT(";"));
}

FString FBridgeHeaderBuilder::IncludeFor(const UField* Field) const
{
    const FString FileName = Field->IsA<UClass>() ? BridgeNaming::ClassesHeaderName(Field)
                                                  : BridgeNaming::StructsHeaderName(Field);
    if (Context.Generated.Contains(Field))
    {
        return FString::Printf(TEXT("#include \"%s\""), *FileName);
    }
    return FString::Printf(TEXT("#include \"%s/%s\""), *Context.SdkInclude, *FileName);
}

FString FBridgeHeaderBuilder::Build(const FString& Banner, const FString& Body) const
{
    TArray<FString> SortedIncludes = Includes.Array();
    SortedIncludes.Sort();
    TArray<FString> SortedDecls = ForwardDecls.Array();
    SortedDecls.Sort();

    FString Out;
    Out += TEXT("#pragma once\n\n");
    Out += TEXT("/*\n* Generated by UEVRBridgeGen. Do not edit by hand.\n* ");
    Out += Banner;
    Out += TEXT("\n*/\n\n");
    Out += FString::Printf(TEXT("#include \"%s/Basic.hpp\"\n"), *Context.SdkInclude);
    Out += TEXT("#include \"Bridge.hpp\"\n");
    for (const FString& Include : SortedIncludes)
    {
        Out += Include + TEXT("\n");
    }
    Out += TEXT("\nnamespace SDK\n{\n");
    for (const FString& Decl : SortedDecls)
    {
        Out += Decl + TEXT("\n");
    }
    if (SortedDecls.Num() > 0)
    {
        Out += TEXT("\n");
    }
    Out += Body;
    Out += TEXT("\n}\n");
    return Out;
}
